"""
Render production's nginx and guard configuration for the local stack.

Everything is written under ``tmp/local-stack/`` (gitignored through ``tmp``):

    etc/guard.yaml             cloud/vps/guard.yaml, copied as is
    etc/guard.local.yaml       cloudflare.dry_run: true, merged on top as on the host
    etc/cloudflare/ips-v4|v6   empty: no Cloudflare in front locally
    nginx/nginx.conf           the stand-in for Ubuntu's /etc/nginx/nginx.conf
    nginx/hpldn.conf           cloud/vps/nginx/hpldn.conf, paths swapped (`SUBSTITUTIONS`)
    nginx/hpldn/               /etc/nginx/hpldn: api_proxy.conf, api_cache.conf and security_headers.conf
                               (paths swapped), render_guard_nginx.py's limit includes,
                               cloudflare_realip.conf (trusts the loopback) and api_key.conf
    guard/                     /var/lib/hpldn-guard: the daemon's state; nginx/banned.conf
                               and nginx/crawlers.conf are seeded empty
    run/, logs/, temp/         pid files and the guard's log socket, logs, nginx's temp files

Every substitution must match at least once, so a reshaped ``hpldn.conf`` fails
the render instead of quietly diverging from production. The only other
differences are plain HTTP on 127.0.0.1:8080 (localhost is a secure context,
so no certificate and no origin-pull client check), gunicorn's socket under
``run/`` instead of ``/run/hpldn-api``, and ``CF-Connecting-IP`` trusted from
the loopback, where production trusts it from Cloudflare's ranges.
"""

import os
import re
import shutil
import subprocess
import sys
from collections.abc import Callable
from dataclasses import dataclass
from pathlib import Path

REPO_ROOT = Path(os.environ.get("HPLDN_DIR_FP") or Path(__file__).resolve().parents[5])
VPS_DIR = Path(__file__).resolve().parents[1] / "vps"
FETCH_SCRIPT = Path(__file__).resolve().with_name("fetch_nginx.sh")

LISTEN = "127.0.0.1:8080"
SERVER_NAMES = "localhost 127.0.0.1"
# sun_path is 108 bytes on Linux, including the terminating NUL.
UNIX_PATH_MAX = 107
GENERATED = "# Generated by hpldn.backend.cloud.local.render from {source}; edit that, not this.\n"
GENERATED_LOCAL = "# Generated by hpldn.backend.cloud.local.render on every `up`: {what}.\n"

# Production paths that must not survive the render (comments are dropped, so
# only directives are checked).
PRODUCTION_PATHS = ("/etc/nginx", "/etc/hpldn", "/var/lib/hpldn-guard", "/run/hpldn-guard", "/run/hpldn-api", "/var/www", "/var/log", "/var/cache", "443")

# Used when no nginx-common mime.types is found; enough for the bundle.
_FALLBACK_MIME_TYPES = """types {
    text/html html;
    text/css css;
    text/plain txt;
    application/javascript js;
    application/json json map;
    application/manifest+json webmanifest;
    image/png png;
    image/svg+xml svg;
    image/x-icon ico;
    font/woff2 woff2;
}
"""


class RenderError(Exception):
    """The production configuration could not be rendered for localhost."""


@dataclass(frozen=True)
class Stack:
    """The local stack's directory layout under `root`."""

    root: Path
    repo: Path = REPO_ROOT

    @classmethod
    def default(cls) -> "Stack":
        return cls(REPO_ROOT / "tmp" / "local-stack")

    @property
    def etc(self) -> Path:
        return self.root / "etc"

    @property
    def guard_config(self) -> Path:
        return self.etc / "guard.yaml"

    @property
    def cloudflare_dir(self) -> Path:
        return self.etc / "cloudflare"

    @property
    def nginx_dir(self) -> Path:
        return self.root / "nginx"

    @property
    def nginx_conf(self) -> Path:
        return self.nginx_dir / "nginx.conf"

    @property
    def site_conf(self) -> Path:
        return self.nginx_dir / "hpldn.conf"

    @property
    def includes(self) -> Path:
        """The stand-in for /etc/nginx/hpldn."""
        return self.nginx_dir / "hpldn"

    @property
    def guard_state(self) -> Path:
        """The stand-in for /var/lib/hpldn-guard."""
        return self.root / "guard"

    @property
    def banned_conf(self) -> Path:
        return self.guard_state / "nginx" / "banned.conf"

    @property
    def crawlers_conf(self) -> Path:
        return self.guard_state / "nginx" / "crawlers.conf"

    @property
    def run(self) -> Path:
        return self.root / "run"

    @property
    def socket(self) -> Path:
        return self.run / "log.sock"

    @property
    def api_socket(self) -> Path:
        """gunicorn's unix socket: the stand-in for /run/hpldn-api/api.sock (hpldn-api.socket)."""
        return self.run / "api.sock"

    @property
    def logs(self) -> Path:
        return self.root / "logs"

    @property
    def api_log(self) -> Path:
        """gunicorn's output, and nginx's lines for the API requests it refuses itself."""
        return self.logs / "api.log"

    @property
    def temp(self) -> Path:
        return self.root / "temp"

    @property
    def nginx_bin(self) -> Path:
        """Where fetch_nginx.sh unpacks the nginx packages."""
        return self.root / "nginx-bin"

    @property
    def build(self) -> Path:
        return self.repo / "src" / "hpldn" / "frontend" / "build"

    def guard_env(self) -> dict[str, str]:
        """The variables that point the API, the guard daemon and its CLI at this stack."""
        return {
            "HPLDN_GUARD_CONFIG": str(self.guard_config),
            "HPLDN_GUARD_STATE_DIR": str(self.guard_state),
            "HPLDN_GUARD_SOCKET": str(self.socket),
            "HPLDN_GUARD_CLOUDFLARE_DIR": str(self.cloudflare_dir),
        }


@dataclass(frozen=True)
class Substitution:
    """One production-to-local rewrite of the copied nginx files."""

    name: str
    pattern: str
    replacement: Callable[[Stack], str]
    flags: int = 0


# Applied in order to hpldn.conf, api_proxy.conf, api_cache.conf and
# security_headers.conf together; each must match at least once across them.
SUBSTITUTIONS: tuple[Substitution, ...] = (
    Substitution(
        "default server: TLS handshake refused -> connection closed",
        r"listen 443 ssl default_server;\n([ \t]*)ssl_reject_handshake on;",
        lambda s: f"listen {LISTEN} default_server;\n\\1return 444;",
    ),
    Substitution("site: listen 443 ssl http2 -> plain HTTP on the loopback", r"listen 443 ssl http2;", lambda s: f"listen {LISTEN};"),
    # The certificate, the TLS settings and the mandatory origin-pull client
    # check: there is no TLS (and no Cloudflare) locally.
    Substitution("site: ssl_* lines dropped", r"^[ \t]*ssl_[a-z_]+[ \t][^\n]*;\n", lambda s: "", re.MULTILINE),
    Substitution("access log: TLS session reuse -> '-' (no TLS)", re.escape("$ssl_session_reused"), lambda s: "-"),
    Substitution("/run/hpldn-api/api.sock", re.escape("/run/hpldn-api/api.sock"), lambda s: str(s.api_socket)),
    Substitution("/etc/nginx/hpldn/", re.escape("/etc/nginx/hpldn/"), lambda s: f"{s.includes}/"),
    Substitution("/var/lib/hpldn-guard/nginx/", re.escape("/var/lib/hpldn-guard/nginx/"), lambda s: f"{s.guard_state}/nginx/"),
    Substitution("/run/hpldn-guard/log.sock", re.escape("/run/hpldn-guard/log.sock"), lambda s: str(s.socket)),
    Substitution("/var/www/hpldn", re.escape("/var/www/hpldn"), lambda s: str(s.build)),
    Substitution("/var/cache/nginx/hpldn", re.escape("/var/cache/nginx/hpldn"), lambda s: str(s.temp / "cache")),
    Substitution("/var/log/nginx/access.log", re.escape("/var/log/nginx/access.log"), lambda s: str(s.logs / "access.log")),
    # The API requests nginx answers itself go into the API's own log, so
    # api.log holds every API request (gunicorn appends to it too).
    Substitution("/var/log/nginx/hpldn-api.log", re.escape("/var/log/nginx/hpldn-api.log"), lambda s: str(s.api_log)),
    Substitution("@SERVER_NAME@", re.escape("@SERVER_NAME@"), lambda s: SERVER_NAMES),
)

# Production file -> where its local copy goes.
COPIED = {
    "hpldn.conf": lambda s: s.site_conf,
    "api_proxy.conf": lambda s: s.includes / "api_proxy.conf",
    "api_cache.conf": lambda s: s.includes / "api_cache.conf",
    "security_headers.conf": lambda s: s.includes / "security_headers.conf",
}


def _strip_comments(text: str) -> str:
    """Drop comment-only lines, which name production paths; directives are left alone."""
    return "".join(line for line in text.splitlines(keepends=True) if not line.lstrip().startswith("#"))


def substitute(sources: dict[str, str], stack: Stack) -> dict[str, str]:
    """
    Return `sources` ({name: production text}) with every `SUBSTITUTIONS` entry applied.

    Raises
    ------
    RenderError
        When an entry matches nothing, or a production path is left.
    """
    texts = {name: _strip_comments(text) for name, text in sources.items()}
    for sub in SUBSTITUTIONS:
        total = 0
        replacement = sub.replacement(stack)
        for name, text in texts.items():
            # A function replacement keeps backslashes in paths literal; \1 is expanded by hand.
            texts[name], count = re.subn(
                sub.pattern,
                lambda m, r=replacement: r.replace("\\1", m.group(1) if m.re.groups else ""),
                text,
                flags=sub.flags,
            )
            total += count
        if total == 0:
            raise RenderError(
                f"substitution {sub.name!r} matched nothing in {', '.join(sources)}: the production "
                "nginx files changed shape; update cloud/local/render.py to match"
            )
    for name, text in texts.items():
        for path in PRODUCTION_PATHS:
            if path in text:
                raise RenderError(f"{name} still holds the production {path!r} after the render")
    return texts


def find_mime_types(nginx: Path | None) -> Path | None:
    """nginx-common's mime.types: beside a binary unpacked by fetch_nginx.sh, else the system's."""
    candidates = []
    if nginx is not None:
        # <root>/usr/sbin/nginx -> <root>/etc/nginx/mime.types
        candidates.append(nginx.resolve().parents[2] / "etc" / "nginx" / "mime.types")
    candidates.append(Path("/etc/nginx/mime.types"))
    return next((path for path in candidates if path.is_file()), None)


def find_nginx(stack: Stack) -> Path | None:
    """The nginx on ``PATH`` (or in /usr/sbin), else the one fetch_nginx.sh unpacked, else None."""
    for found in (shutil.which("nginx"), shutil.which("nginx", path="/usr/sbin")):
        if found:
            return Path(found)
    local = stack.nginx_bin / "usr" / "sbin" / "nginx"
    return local if local.is_file() else None


def fetch_nginx(stack: Stack) -> Path:
    """Unpack Ubuntu's nginx packages into the stack with fetch_nginx.sh (no sudo); return the binary."""
    subprocess.run(["bash", str(FETCH_SCRIPT), str(stack.nginx_bin)], check=True)
    binary = stack.nginx_bin / "usr" / "sbin" / "nginx"
    if not binary.is_file():
        raise RenderError(f"fetch_nginx.sh did not produce {binary}")
    return binary


def nginx_command(stack: Stack, binary: Path, *args: str) -> list[str]:
    """``nginx`` with the stack's prefix, configuration and error log."""
    return [str(binary), "-p", f"{stack.root}/", "-c", str(stack.nginx_conf), "-e", str(stack.logs / "error.log"), *args]


def _nginx_conf(stack: Stack, mime_types: Path) -> str:
    temp = stack.temp
    # Ubuntu's file says `auto`: one worker per CPU of the host. nginx counts the
    # machine's CPUs, not the stack's scope, so the count is written out.
    workers = len(os.sched_getaffinity(0))
    return (
        GENERATED_LOCAL.format(what="the stand-in for Ubuntu's /etc/nginx/nginx.conf")
        + f"""worker_processes {workers};
pid {stack.run / "nginx.pid"};
error_log {stack.logs / "error.log"} notice;

events {{
    worker_connections 768;
}}

http {{
    sendfile on;
    tcp_nopush on;
    types_hash_max_size 2048;
    include {mime_types};
    default_type application/octet-stream;

    client_body_temp_path {temp / "body"};
    proxy_temp_path {temp / "proxy"};
    fastcgi_temp_path {temp / "fastcgi"};
    uwsgi_temp_path {temp / "uwsgi"};
    scgi_temp_path {temp / "scgi"};

    access_log {stack.logs / "access.log"};
    gzip on;

    # /etc/nginx/conf.d/hpldn.conf on the host.
    include {stack.site_conf};
}}
"""
    )


def _write(path: Path, text: str, mode: int = 0o644) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_name(f".{path.name}.tmp")
    tmp.write_text(text, encoding="utf-8")
    tmp.chmod(mode)
    tmp.replace(path)


def render(stack: Stack, *, api_key: str, nginx: Path | None = None) -> None:
    """
    Write the local stack's configuration under ``stack.root``.

    Parameters
    ----------
    stack : Stack
        Where to write.
    api_key : str
        ``HPLDN_API_KEY`` from ``develop.env``, which nginx adds to every proxied call.
    nginx : Path, optional
        The binary that will run it, to find nginx-common's ``mime.types``.

    Raises
    ------
    RenderError
        On an unusable key, a failed guard render, or a substitution that no
        longer matches the production files.
    """
    for sock in (stack.socket, stack.api_socket):
        if len(str(sock).encode()) > UNIX_PATH_MAX:
            raise RenderError(f"{sock} is longer than a unix socket path may be ({UNIX_PATH_MAX} bytes)")
    if not re.fullmatch(r"[A-Za-z0-9]+", api_key or ""):
        raise RenderError("HPLDN_API_KEY in develop.env is missing or not alphanumeric (it is written into nginx syntax)")
    for directory in (
        stack.etc,
        stack.cloudflare_dir,
        stack.includes,
        stack.guard_state / "nginx",
        stack.run,
        stack.logs,
        *(stack.temp / name for name in ("body", "proxy", "fastcgi", "uwsgi", "scgi", "cache")),
    ):
        directory.mkdir(parents=True, exist_ok=True)

    # guard.yaml and the host-only override, read by the API, the daemon and the renderer.
    shutil.copyfile(VPS_DIR / "guard.yaml", stack.guard_config)
    _write(
        stack.etc / "guard.local.yaml",
        GENERATED_LOCAL.format(what="never send the bans to Cloudflare from a laptop")
        + "cloudflare:\n  dry_run: true\n",
    )

    # The limit includes, with the same script bootstrap.sh runs.
    result = subprocess.run(
        [sys.executable, str(VPS_DIR / "render_guard_nginx.py"), "--config", str(stack.guard_config), "--out", str(stack.includes)],
        capture_output=True,
        text=True,
    )
    if result.returncode != 0:
        raise RenderError(result.stderr.strip() or "render_guard_nginx.py failed")

    sources = {name: (VPS_DIR / "nginx" / name).read_text(encoding="utf-8") for name in COPIED}
    for name, text in substitute(sources, stack).items():
        _write(COPIED[name](stack), GENERATED.format(source=f"cloud/vps/nginx/{name}") + text)

    # On the host: hpldn-cloudflare-ips writes Cloudflare's ranges; here the
    # only hop in front is the loopback (the dev server or a test).
    _write(
        stack.includes / "cloudflare_realip.conf",
        GENERATED_LOCAL.format(what="CF-Connecting-IP trusted from the loopback only")
        + "set_real_ip_from 127.0.0.1;\nset_real_ip_from ::1;\nreal_ip_header CF-Connecting-IP;\n",
    )
    _write(stack.includes / "api_key.conf", f'proxy_set_header X-API-Key "{api_key}";\n', mode=0o600)

    # Seeded empty as bootstrap.sh does; never overwritten, they hold the bans.
    for seed in (stack.banned_conf, stack.crawlers_conf, *(stack.cloudflare_dir / n for n in ("ips-v4", "ips-v6"))):
        if not seed.exists():
            seed.touch()

    mime_types = find_mime_types(nginx)
    if mime_types is None:
        mime_types = stack.nginx_dir / "mime.types"
        _write(mime_types, _FALLBACK_MIME_TYPES)
    _write(stack.nginx_conf, _nginx_conf(stack, mime_types))
