#!/usr/bin/env python3
"""
Render nginx's rate limits and user-agent rules from guard.yaml.

    python3 render_guard_nginx.py --config /etc/hpldn/guard.yaml --out /etc/nginx/hpldn

Run by bootstrap.sh (configure_nginx) under the system python3 with
python3-yaml, before any virtualenv exists, so it uses nothing else and does
not import the hpldn package; hpldn.backend.guard.config validates the same
file for the API and the daemon. guard.local.yaml beside the config is
deep-merged on top, as there. Writes, into --out:

  limits_http.conf    the limit_req_zone/limit_conn_zone directives, and the
                      maps that key verified crawlers ($hpldn_crawler, from
                      the guard's crawlers.conf) on the crawler zone only and
                      everyone else on the other zones only (http level)
  server_limits.conf  the per-client connection cap and the timeouts against
                      slow clients (server level)
  limits/<route>.conf one per location of hpldn.conf, with its limit_req lines
  bad_ua.conf         $hpldn_deny_ua: 1 for an /api request whose user agent
                      is denied, unless it comes from a crawler range

A file is only rewritten when its content changes. Exit status 1 with a message
on an invalid config; nginx -t then checks the result.
"""

import argparse
import re
import sys
from pathlib import Path

import yaml

LOCAL_NAME = "guard.local.yaml"
ZONE_PREFIX = "hpldn_"
GENERATED = "# Generated by render_guard_nginx.py from guard.yaml; edit that, not this.\n"

_DURATION = re.compile(r"^\s*(\d+)\s*([smhd]?)\s*$")
_UNITS = {"": 1, "s": 1, "m": 60, "h": 3600, "d": 86400}
_RATE = re.compile(r"^\d+r/[sm]$")
_SIZE = re.compile(r"^\d+[km]$")
_NAME = re.compile(r"^[a-z][a-z0-9_]*$")
# User-agent tokens go into nginx regexes; anything else would need escaping.
_UA_TOKEN = re.compile(r"^[A-Za-z0-9 ._/-]*$")


class ConfigError(Exception):
    pass


def deep_merge(base: dict, override: dict) -> dict:
    merged = dict(base)
    for key, value in override.items():
        if isinstance(value, dict) and isinstance(merged.get(key), dict):
            merged[key] = deep_merge(merged[key], value)
        else:
            merged[key] = value
    return merged


def load(path: Path) -> dict:
    """Read `path` and the guard.local.yaml beside it."""
    def read(p: Path) -> dict:
        data = yaml.safe_load(p.read_text(encoding="utf-8")) or {}
        if not isinstance(data, dict):
            raise ConfigError(f"{p} must hold a mapping")
        return data

    data = read(path)
    local = path.with_name(LOCAL_NAME)
    if local.is_file():
        data = deep_merge(data, read(local))
    return data


def _get(data: dict, dotted: str):
    node = data
    for part in dotted.split("."):
        if not isinstance(node, dict) or part not in node:
            raise ConfigError(f"guard.yaml has no {dotted}")
        node = node[part]
    return node


def seconds(value, where: str) -> int:
    if isinstance(value, int) and not isinstance(value, bool) and value > 0:
        return value
    match = _DURATION.match(str(value))
    if not match or int(match.group(1)) <= 0:
        raise ConfigError(f"{where}: not a whole-second duration: {value!r}")
    return int(match.group(1)) * _UNITS[match.group(2)]


def _int(value, where: str, minimum: int = 0) -> int:
    if not isinstance(value, int) or isinstance(value, bool) or value < minimum:
        raise ConfigError(f"{where}: expected a whole number >= {minimum}, not {value!r}")
    return value


def render(data: dict) -> dict[str, str]:
    """Return {relative path: content} for every file this script owns."""
    nginx = _get(data, "rate_limits.nginx")
    zones = _get(nginx, "zones") if isinstance(nginx, dict) else None
    routes = nginx.get("routes")
    if not isinstance(zones, dict) or "crawler" not in zones:
        raise ConfigError("rate_limits.nginx.zones needs a crawler zone")
    if not isinstance(routes, dict) or not routes:
        raise ConfigError("rate_limits.nginx.routes is empty")

    http = [
        GENERATED,
        "# Verified crawlers ($hpldn_crawler, from the guard's crawlers.conf) are\n"
        "# counted on the crawler zone only, everyone else on the others only: an\n"
        "# empty key is not counted.\n",
        'map $hpldn_crawler $hpldn_limit_key {\n    1 "";\n    default $binary_remote_addr;\n}\n',
        'map $hpldn_crawler $hpldn_crawler_key {\n    1 $binary_remote_addr;\n    default "";\n}\n',
    ]
    for name, zone in zones.items():
        where = f"rate_limits.nginx.zones.{name}"
        if not _NAME.match(str(name)) or not isinstance(zone, dict):
            raise ConfigError(f"{where}: bad zone")
        rate, size = str(zone.get("rate", "")), str(zone.get("size", "10m"))
        if not _RATE.match(rate):
            raise ConfigError(f"{where}.rate: {rate!r} is not like 60r/m or 10r/s")
        if not _SIZE.match(size):
            raise ConfigError(f"{where}.size: {size!r} is not like 10m")
        key = "$hpldn_crawler_key" if name == "crawler" else "$hpldn_limit_key"
        http.append(f"limit_req_zone {key} zone={ZONE_PREFIX}{name}:{size} rate={rate};\n")
    http.append(f"limit_conn_zone $binary_remote_addr zone={ZONE_PREFIX}conn:10m;\n")
    http.append(f"limit_conn_zone $binary_remote_addr zone={ZONE_PREFIX}search_conn:10m;\n")

    conn = _int(nginx.get("conn_per_client"), "rate_limits.nginx.conn_per_client", 1)
    search_conn = _int(nginx.get("search_conn_per_client"), "rate_limits.nginx.search_conn_per_client", 1)
    timeouts = _get(nginx, "timeouts")
    server = [
        GENERATED,
        "# All requests of one client open at once, across the site.\n",
        f"limit_conn {ZONE_PREFIX}conn {conn};\n",
        "# Slow clients are cut off.\n",
        f"client_header_timeout {seconds(timeouts.get('client_header'), 'timeouts.client_header')}s;\n",
        f"client_body_timeout {seconds(timeouts.get('client_body'), 'timeouts.client_body')}s;\n",
        f"send_timeout {seconds(timeouts.get('send'), 'timeouts.send')}s;\n",
        f"keepalive_timeout {seconds(timeouts.get('keepalive'), 'timeouts.keepalive')}s;\n",
    ]

    crawler_burst = _int(zones["crawler"].get("burst", 20), "rate_limits.nginx.zones.crawler.burst")
    files = {"limits_http.conf": "".join(http), "server_limits.conf": "".join(server)}
    for name, route in routes.items():
        where = f"rate_limits.nginx.routes.{name}"
        if not _NAME.match(str(name)) or not isinstance(route, dict):
            raise ConfigError(f"{where}: bad route")
        zone = route.get("zone")
        if zone not in zones or zone == "crawler":
            raise ConfigError(f"{where}.zone: unknown zone {zone!r}")
        burst = _int(route.get("burst"), f"{where}.burst")
        lines = [
            GENERATED,
            f"# location {route.get('location', '?')}\n",
            f"limit_req zone={ZONE_PREFIX}{zone} burst={burst} nodelay;\n",
            f"limit_req zone={ZONE_PREFIX}crawler burst={crawler_burst} nodelay;\n",
            # A location's own limit_conn replaces the server's, so repeat it.
            f"limit_conn {ZONE_PREFIX}conn {conn};\n",
        ]
        if route.get("search_conn"):
            lines.append(f"limit_conn {ZONE_PREFIX}search_conn {search_conn};\n")
        files[f"limits/{name}.conf"] = "".join(lines)

    tokens = _get(data, "user_agents.deny_on_api")
    if not isinstance(tokens, list):
        raise ConfigError("user_agents.deny_on_api must be a list")
    ua = [GENERATED, "map $http_user_agent $hpldn_bad_ua {\n    default 0;\n"]
    for token in tokens:
        token = "" if token is None else str(token)
        if not _UA_TOKEN.match(token):
            raise ConfigError(f"user_agents.deny_on_api: {token!r} may only hold letters, digits, space and ._/-")
        if token == "":
            ua.append('    "" 1;\n')
        else:
            pattern = re.sub(r"([./])", r"\\\1", token)
            ua.append(f'    "~*{pattern}" 1;\n')
    ua.append("}\n")
    ua.append(
        "# Denied only on /api, and never for a crawler range.\n"
        'map "$hpldn_crawler:$hpldn_bad_ua:$uri" $hpldn_deny_ua {\n'
        "    default 0;\n"
        '    "~^0:1:/api/" 1;\n'
        "}\n"
    )
    files["bad_ua.conf"] = "".join(ua)
    return files


def write(out: Path, files: dict[str, str]) -> list[str]:
    """Write `files` under `out`, removing stale limits/*.conf; returns the paths changed."""
    changed = []
    (out / "limits").mkdir(parents=True, exist_ok=True)
    for rel, text in files.items():
        path = out / rel
        if path.is_file() and path.read_text(encoding="utf-8") == text:
            continue
        tmp = path.with_name(f".{path.name}.tmp")
        tmp.write_text(text, encoding="utf-8")
        tmp.chmod(0o644)
        tmp.replace(path)
        changed.append(rel)
    for stale in (out / "limits").glob("*.conf"):
        if f"limits/{stale.name}" not in files:
            stale.unlink()
            changed.append(f"limits/{stale.name} (removed)")
    return changed


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--config", type=Path, default=Path("/etc/hpldn/guard.yaml"))
    parser.add_argument("--out", type=Path, default=Path("/etc/nginx/hpldn"))
    args = parser.parse_args(argv)
    try:
        files = render(load(args.config))
    except (ConfigError, OSError, yaml.YAMLError) as exc:
        print(f"render_guard_nginx: {args.config}: {exc}", file=sys.stderr)
        return 1
    changed = write(args.out, files)
    print(f"render_guard_nginx: {len(files)} files in {args.out}, {len(changed)} changed", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
