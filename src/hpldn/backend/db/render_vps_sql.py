"""
Render the serving host's ``api_role.sql`` and ``grants.sql`` from ``db/sql``.

The API role's settings and read grants have one source,
``db/sql/fragments/``, which the local scripts include with ``\\ir``/``\\i``.
The serving host gets them as two self-contained files, because
``bootstrap.sh`` installs them on their own into ``/usr/local/share/hpldn``.
They are build output, not tracked: ``deploy.sh`` runs this before it
pushes the bundle::

    python -m hpldn.backend.db.render_vps_sql            # write them
    python -m hpldn.backend.db.render_vps_sql --check    # exit 1 if stale
"""

import argparse
import sys
from pathlib import Path
from typing import Dict

from hpldn.backend.db import SQL_DIR

FRAGMENTS = SQL_DIR / "fragments"
VPS_POSTGRES_DIR = Path(__file__).resolve().parents[1] / "cloud" / "vps" / "postgres"

_GENERATED = "-- GENERATED by `python -m hpldn.backend.db.render_vps_sql`; do not edit.\n"

_API_ROLE_HEADER = """\
-- =====================================================================
-- The read API's database role on the serving host.
--
-- Settings from db/sql/fragments/api_role_settings.sql (the same file
-- db_enable_api_login.sh applies locally), the database lockdown from
-- db/sql/fragments/serving_db_lockdown.sql, and the owner role and peer
-- login from db/sql/fragments/serving_owner.sql. There is no password: the
-- API logs in with peer authentication over the unix socket (pg_hba.conf,
-- pg_ident.conf), as the OS user hpldn only.
--
-- Run as postgres, idempotent:
--     psql -v ON_ERROR_STOP=1 -v api_role=hpldn_api -v db=hpldn_serve -f api_role.sql
-- =====================================================================

\\if :{?api_role} \\else \\set api_role hpldn_api \\endif
\\if :{?db} \\else \\set db hpldn_serve \\endif

SELECT format('CREATE ROLE %I NOLOGIN', :'api_role')
WHERE NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = :'api_role') \\gexec
"""

_GRANTS_HEADER = """\
-- =====================================================================
-- Read grants for the API role on a serving schema.
--
-- From db/sql/fragments/api_grants.sql, the same file
-- db_grants_post_migration.sql applies locally. restore_serving_db.sh runs
-- it against production_next BEFORE the blue/green swap, so the API never
-- sees the new tables without its grants. ALTER DEFAULT PRIVILEGES is not
-- needed: nothing creates tables here except the restore, which re-runs
-- this file.
--
-- Run as postgres:
--     psql -v ON_ERROR_STOP=1 -v schema=production_next -v api_role=hpldn_api -f grants.sql
-- =====================================================================

\\if :{?api_role} \\else \\set api_role hpldn_api \\endif
\\if :{?schema} \\else \\set schema production \\endif
"""


def _fragment(name: str) -> str:
    return f"\n-- ---- db/sql/fragments/{name} ----\n" + (FRAGMENTS / name).read_text()


def render() -> Dict[str, str]:
    """Return ``{file name: content}`` for the serving host's two SQL files."""
    return {
        "api_role.sql": _GENERATED
        + _API_ROLE_HEADER
        + _fragment("api_role_settings.sql")
        + _fragment("serving_db_lockdown.sql")
        + _fragment("serving_owner.sql"),
        "grants.sql": _GENERATED + _GRANTS_HEADER + _fragment("api_grants.sql"),
    }


def write(out_dir: Path = VPS_POSTGRES_DIR) -> list:
    """Write the rendered files into `out_dir`; return their paths."""
    paths = []
    for name, content in render().items():
        path = out_dir / name
        path.write_text(content)
        paths.append(path)
    return paths


def stale(out_dir: Path = VPS_POSTGRES_DIR) -> list:
    """Return the names of the rendered files missing from `out_dir` or differing from the source."""
    return [
        name
        for name, content in render().items()
        if not (out_dir / name).is_file() or (out_dir / name).read_text() != content
    ]


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--out-dir", type=Path, default=VPS_POSTGRES_DIR)
    parser.add_argument("--check", action="store_true", help="exit 1 when a rendered file is missing or stale")
    args = parser.parse_args(argv)
    if args.check:
        bad = stale(args.out_dir)
        for name in bad:
            print(f"render_vps_sql: {args.out_dir / name} is missing or stale", file=sys.stderr)
        return 1 if bad else 0
    for path in write(args.out_dir):
        print(f"render_vps_sql: wrote {path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
